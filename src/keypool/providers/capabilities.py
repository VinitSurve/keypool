"""Provider capability metadata and comprehensive provider registry catalog."""

from __future__ import annotations

from enum import StrEnum

from pydantic import BaseModel, ConfigDict, Field


class ProviderCategory(StrEnum):
    """Categorization of supported AI provider services."""

    MAJOR = "major"
    INFERENCE = "inference"
    INTERNATIONAL = "international"
    ENTERPRISE = "enterprise"
    LOCAL = "local"
    GENERIC = "generic"
    CUSTOM = "custom"


class ProviderAPIType(StrEnum):
    """Underlying REST API protocol dialect."""

    OPENAI_COMPATIBLE = "openai_compatible"
    ANTHROPIC = "anthropic"
    GEMINI = "gemini"
    COHERE = "cohere"
    REPLICATE = "replicate"
    AWS_BEDROCK = "aws_bedrock"
    CUSTOM = "custom"


class AuthType(StrEnum):
    """Authentication mechanism required by the provider API."""

    BEARER_TOKEN = "bearer_token"  # noqa: S105
    API_KEY_HEADER = "api_key_header"
    URL_PARAM = "url_param"
    NONE_REQUIRED = "none_required"
    CLOUD_IAM = "cloud_iam"


class ProviderCapability(StrEnum):
    """Standardized model capability flags."""

    STREAMING = "streaming"
    TOOL_CALLING = "tool_calling"
    JSON_MODE = "json_mode"
    VISION = "vision"
    EMBEDDINGS = "embeddings"
    REASONING = "reasoning"


class ProviderMetadata(BaseModel):
    """Complete public capability metadata for an AI provider."""

    model_config = ConfigDict(frozen=True)

    name: str
    display_name: str
    category: ProviderCategory
    api_type: ProviderAPIType
    auth_type: AuthType
    env_var_name: str
    base_url: str
    default_test_model: str
    docs_url: str
    models_docs_url: str | None = None
    rate_limits_docs_url: str | None = None
    supported_endpoints: list[str] = Field(default_factory=lambda: ["/chat/completions", "/models"])
    capabilities: list[ProviderCapability] = Field(
        default_factory=lambda: [
            ProviderCapability.STREAMING,
            ProviderCapability.TOOL_CALLING,
            ProviderCapability.JSON_MODE,
        ]
    )
    usage_extraction_supported: bool = True
    known_limitations: str | None = None


